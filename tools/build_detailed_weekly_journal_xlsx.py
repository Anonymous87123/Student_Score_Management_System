def build_sheet(workbook: xlsxwriter.Workbook, sheet_name: str, week_info: dict) -> None:
    ws = workbook.add_worksheet(sheet_name)
    ws.freeze_panes(5, 1)
    ws.set_zoom(90)
    ws.set_column("A:A", 10)
    ws.set_column("B:B", 44)
    ws.set_column("C:C", 56)
    ws.set_column("D:D", 56)

    title_fmt = workbook.add_format(
        {
            "bold": True,
            "font_size": 16,
            "align": "center",
            "valign": "vcenter",
            "border": 1,
        }
    )
    label_fmt = workbook.add_format(
        {
            "bold": True,
            "align": "center",
            "valign": "vcenter",
            "border": 1,
        }
    )
    value_fmt = workbook.add_format(
        {
            "align": "left",
            "valign": "vcenter",
            "border": 1,
        }
    )
    header_fmt = workbook.add_format(
        {
            "bold": True,
            "align": "center",
            "valign": "vcenter",
            "border": 1,
            "bg_color": "#D9E2F3",
        }
    )
    day_fmt = workbook.add_format(
        {
            "bold": True,
            "align": "center",
            "valign": "vcenter",
            "border": 1,
            "bg_color": "#F2F2F2",
        }
    )
    text_fmt = workbook.add_format(
        {
            "text_wrap": True,
            "align": "left",
            "valign": "top",
            "border": 1,
        }
    )

    ws.merge_range("A1:D1", TITLE, title_fmt)
    ws.write("A3", "组序号：", label_fmt)
    ws.write("B3", "", value_fmt)
    ws.write("C3", "课题名称：", label_fmt)
    ws.write("D3", PROJECT_NAME, value_fmt)
    ws.write("A4", "姓名：", label_fmt)
    ws.write("B4", "", value_fmt)
    ws.write("C4", "队友姓名：", label_fmt)
    ws.write("D4", "", value_fmt)
    ws.write("A5", "", header_fmt)
    ws.write("B5", "计划安排", header_fmt)
    ws.write("C5", "工作内容", header_fmt)
    ws.write("D5", "工作总结", header_fmt)

    start_row = 5
    for day_name, day_info in zip(DAYS, week_info["days"]):
        end_row = start_row + 2
        for row in range(start_row, end_row + 1):
            ws.set_row(row, 42)
        ws.merge_range(start_row, 0, end_row, 0, day_name, day_fmt)
        ws.merge_range(start_row, 1, end_row, 1, make_plan(week_info["theme"], day_info), text_fmt)
        ws.merge_range(start_row, 2, end_row, 2, make_work(day_info), text_fmt)
        ws.merge_range(start_row, 3, end_row, 3, make_summary(day_info), text_fmt)
        start_row += 3


def main() -> None:
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    workbook = xlsxwriter.Workbook(str(OUTPUT))
    try:
        for sheet_name, week_info in WEEKS.items():
            build_sheet(workbook, sheet_name, week_info)
    finally:
        workbook.close()


if __name__ == "__main__":
    main()
